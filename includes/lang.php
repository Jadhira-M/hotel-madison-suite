function translateVisibleTextSegment($text, $map, $currentLang)
{
    $text = repairSpanishText($text);

    if ($currentLang === "es" || trim($text) === "") {
        return $text;
    }

    if (!preg_match("/^(\s*)(.*?)(\s*)$/su", $text, $matches)) {
        return $text;
    }

    $key = normalizeTranslationText($matches[2]);

    if (isset($map[$key])) {
        return $matches[1] . $map[$key] . $matches[3];
    }

    $translatedText = $text;
    foreach (publicTranslationFragments($currentLang) as $from => $to) {
        $translatedText = str_replace(repairSpanishText($from), repairSpanishText($to), $translatedText);
    }

    if ($translatedText !== $text) {
        return $translatedText;
    }

    return $text;
}

function translatePublicHtml($html)
{
    global $currentLang;

    if (strpos($_SERVER["SCRIPT_NAME"] ?? "", "/admin/") !== false) {
        return $html;
    }

    $map = normalizedPublicTranslationMap($currentLang);
    $parts = preg_split("/(<[^>]+>)/", $html, -1, PREG_SPLIT_DELIM_CAPTURE);

    foreach ($parts as $index => $part) {
        if ($part === "" || str_starts_with($part, "<")) {
            continue;
        }

        $parts[$index] = translateVisibleTextSegment($part, $map, $currentLang);
    }

    return implode("", $parts);
}

