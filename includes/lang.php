function normalizeTranslationText($text)
{
    $text = html_entity_decode($text, ENT_QUOTES | ENT_HTML5, "UTF-8");
    return preg_replace("/\s+/u", " ", trim($text));
}

function normalizedPublicTranslationMap($lang)
{
    $extraMap = [];
    $extraPath = __DIR__ . "/lang_extra.php";
    if (is_file($extraPath)) {
        $allExtraMaps = include $extraPath;
        $extraMap = is_array($allExtraMaps[$lang] ?? null) ? $allExtraMaps[$lang] : [];
    }

    $morePath = __DIR__ . "/lang_more.php";
    if (is_file($morePath)) {
        $allMoreMaps = include $morePath;
        if (is_array($allMoreMaps[$lang] ?? null)) {
            $extraMap = array_merge($extraMap, $allMoreMaps[$lang]);
        }
    }

    $rawMap = array_merge(publicTranslationMap($lang), publicTranslationOverrides($lang), $extraMap);
    $map = [];

    foreach ($rawMap as $key => $value) {
        $map[normalizeTranslationText(repairSpanishText($key))] = repairSpanishText($value);
    }

    return $map;
}

